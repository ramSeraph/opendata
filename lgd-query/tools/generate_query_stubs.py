"""Generate editor-visible query signatures; --check detects stale stubs.

Run with PYTHONPATH=src python tools/generate_query_stubs.py from lgd-query/.
No DuckDB installation or source data is required.
"""

import argparse
from inspect import Parameter, signature
from pathlib import Path

from lgd_query import queries


HEADER = '''# Generated by tools/generate_query_stubs.py; do not edit.
from collections.abc import Sequence
from datetime import date
from typing import Literal
from duckdb import DuckDBPyConnection, DuckDBPyRelation
from ..metadata import Dataset, Release
from ._common import DistanceMetric, SearchMode
from ._missing import Columns

Kind = Literal['state', 'ut']
NameField = Literal['english', 'local']

'''


def function(name, method):
    sig = signature(method)
    parts, star = [], False
    for p in sig.parameters.values():
        if p.kind == Parameter.KEYWORD_ONLY and not star:
            parts.append('*')
            star = True
        annotation = p.annotation
        if annotation is Parameter.empty:
            raise ValueError(f'Missing annotation: {name}.{p.name}')
        item = f'{p.name}: {annotation}'
        if p.default is not Parameter.empty:
            item += ' = ...'
        parts.append(item)
    return f'def {name}(\n    ' + ',\n    '.join(parts) + '\n) -> DuckDBPyRelation: ...\n\n'


def render(dataset):
    module = queries.get(dataset)
    text = HEADER
    for name in ('list', 'by_code', 'by_id', 'by_census_code', 'search', 'entities', 'references', 'reference_types'):
        if hasattr(module, name):
            text += function(name, getattr(module, name))
    if hasattr(module, '_queries'):
        text += 'filters: tuple[str, ...]\nname_fields: tuple[str, ...]\ncensus_years: tuple[int, ...]\n\n'
        extra = (', include_entity_name: bool = ..., entity_name: str | None = ..., '
                 'entity_name_status: Literal["matched", "missing", "ambiguous"] | None = ..., '
                 'is_null: Columns = ..., is_blank: Columns = ...'
                 if dataset in ('state_org_units', 'central_org_units') else '')
        text += f'def required_datasets(*, field: str | None = ...{extra}) -> tuple[str, ...]: ...\n\n'
    else:
        text += 'columns: tuple[str, ...]\n\n'
    if hasattr(module, 'entities'):
        annotation = 'str' if dataset in ('org_unit_coverage', 'constituency_coverage') else 'str | int'
        scope = ', *, state_code: str | int | None = ...' if hasattr(module, 'references') else ''
        source_scope = ', state_code: str | int | None = ...' if hasattr(module, 'references') else ''
        text += f'def required_entity_datasets(entity_type: {annotation}{scope}) -> tuple[str, ...]: ...\n'
        text += f'def entity_sources(release: Release, entity_type: {annotation}, *, observed_on: str | None = ...{source_scope}) -> tuple[Dataset, ...]: ...\n\n'
    if hasattr(module, 'references'):
        text += f'''entity_type_filter: str
def reference_type_map() -> tuple[dict[str, object], ...]: ...
def required_reference_datasets(reference_type: {annotation} | None = ..., *, state_code: str | int | None = ...) -> tuple[str, ...]: ...
def reference_sources(release: Release, reference_type: {annotation} | None = ..., *, state_code: str | int | None = ..., observed_on: str | None = ...) -> tuple[Dataset, ...]: ...
'''
    if hasattr(module, 'eci_codes'):
        text += '''eci_levels: tuple[str, ...]
def eci_codes(connection: DuckDBPyConnection, *, level: Literal['parliament', 'assembly'],
              constituency_code: str | int | None = ..., state_code: str | int | None = ...,
              eci_code: str | int | None = ...) -> DuckDBPyRelation: ...
'''
    return text.rstrip() + '\n'


def outputs():
    result = {name + '.pyi': render(name) for name in queries.DATASETS}
    result['__init__.pyi'] = ('# Generated by tools/generate_query_stubs.py; do not edit.\n'
        'from ._catalog import DATASETS as DATASETS, get as get, required_datasets as required_datasets, sources as sources\n'
        'from ._prepared import PreparedQuery as PreparedQuery, prepare as prepare\n' +
        ''.join(f'from . import {name} as {name}\n' for name in queries.DATASETS))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / 'src/lgd_query/queries'
    for name, content in outputs().items():
        path = root / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Stale query stub: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
